#!/usr/bin/env python3
# sndtest_ref.py <snd_main.c> > sndref.c: the PC mixer's gain code, cut out of src/sound/snd_main.c
# as it is (channel_t, is_listener, spatialise, S_SoundLevel, S_DistanceGain) for tools/nds/sndtest.c,
# which checks the DS's fixed-point version (src/platform/nds/sndmath_nds.h) against it.
# ISC licence, see LICENSE.
import re, sys
src = open(sys.argv[1]).read()

def block(start_re):
    m = re.search(start_re, src, re.M)
    if not m:
        sys.exit('sndtest_ref: no match for ' + start_re)
    i = src.index('{', m.start())
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '{':
            depth += 1
        elif src[j] == '}':
            depth -= 1
            if depth == 0:
                end = j + 1
                if src.startswith(' channel_t;', end):
                    end += len(' channel_t;')
                return src[m.start():end] + '\n'
    sys.exit('sndtest_ref: unbalanced ' + start_re)

out = ['/* generated by tools/nds/sndtest_ref.py from ' + sys.argv[1] + ' */\n']
out.append(block(r'^typedef struct \{\n\tsfx_t \*sfx;'))
out.append('static bool entity_origin(const channel_t *ch, float *out) { (void)ch; (void)out; return false; }\n')
out.append(block(r'^static bool is_listener\(const channel_t \*ch\)'))
out.append('float S_SoundLevel(float attenuation);\nfloat S_DistanceGain(float attenuation, float dist);\n')
out.append(block(r'^static void spatialise\(channel_t \*ch\)'))
out.append(block(r'^float S_SoundLevel\(float attenuation\)'))
out.append(block(r'^float S_DistanceGain\(float attenuation, float dist\)'))
sys.stdout.write(''.join(out))
