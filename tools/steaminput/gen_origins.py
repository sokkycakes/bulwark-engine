#!/usr/bin/env python3
"""Generate src/client/steaminput_origins.h: each EInputActionOrigin value
Steam reports, as the controller family and the button whose glyph shows it.

The values come from the order of the EInputActionOrigin enum in the
Steamworks SDK (isteaminput.h), or from a binding that copies it with the
same order (Steamworks.NET's SteamEnums.cs). Only names and their positions
are read; nothing of the SDK is copied into the output.

    python3 tools/steaminput/gen_origins.py path/to/isteaminput.h > src/client/steaminput_origins.h
"""
import re
import sys

def origins(text):
    start = text.index('enum EInputActionOrigin')
    body = text[text.index('{', start) + 1:]
    depth, end = 1, 0
    for i, c in enumerate(body):
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if not depth:
                end = i
                break
    v = -1
    for m in re.finditer(r'k_EInputActionOrigin_(\w+)\s*(?:=\s*(\d+))?\s*,', body[:end]):
        v = int(m.group(2)) if m.group(2) else v + 1
        yield v, m.group(1)

# family prefix -> glyph set (steaminput.h SI_SET_*). The 2026 Steam
# Controller and the Steam Frame's controllers share the Deck's layout
# (sticks, two trackpads, L4/L5/R4/R5), and Xelu has no art for them, so
# they get the Deck's glyphs.
FAMILY = {
    'SteamController': 'STEAMCONTROLLER', 'PS4': 'PS4', 'XBoxOne': 'XBOX', 'XBox360': 'XBOX360',
    'Switch': 'SWITCH', 'PS5': 'PS5', 'SteamDeck': 'STEAMDECK', 'Horipad': 'SWITCH',
    'LenovoLegionGo': 'XBOX', 'Generic': 'XBOX', 'Switch2': 'SWITCH',
    'SteamController2026': 'STEAMDECK', 'SteamFrameController': 'STEAMDECK',
}

# face buttons by their label, per family, to their position
FACE = {
    'Switch': {'A': 'EAST', 'B': 'SOUTH', 'X': 'NORTH', 'Y': 'WEST'},
    'Switch2': {'A': 'EAST', 'B': 'SOUTH', 'X': 'NORTH', 'Y': 'WEST'},
    'Horipad': {'A': 'EAST', 'B': 'SOUTH', 'X': 'NORTH', 'Y': 'WEST'},
    'PS4': {'X': 'SOUTH', 'Circle': 'EAST', 'Square': 'WEST', 'Triangle': 'NORTH'},
    'PS5': {'X': 'SOUTH', 'Circle': 'EAST', 'Square': 'WEST', 'Triangle': 'NORTH'},
}
DEFAULT_FACE = {'A': 'SOUTH', 'B': 'EAST', 'X': 'WEST', 'Y': 'NORTH'}

RULES = [
    (r'(LeftBumper|L1|LB)$', 'LB'), (r'(RightBumper|R1|RB)$', 'RB'),
    (r'(LeftTrigger_\w+|L2(_SoftPull)?|LT(_SoftPull)?)$', 'LT'),
    (r'(RightTrigger_\w+|R2(_SoftPull)?|RT(_SoftPull)?)$', 'RT'),
    (r'(LeftStick_Click|L3|LS)$', 'LCLICK'), (r'(RightStick_Click|R3|RS)$', 'RCLICK'),
    (r'LeftStick_\w+$', 'LSTICK'), (r'RightStick_\w+$', 'RSTICK'),
    (r'DPad_North$', 'DUP'), (r'DPad_South$', 'DDOWN'), (r'DPad_West$', 'DLEFT'), (r'DPad_East$', 'DRIGHT'),
    (r'DPad_Move$', 'DPAD'),
    (r'(Start|Menu|Options?|Plus)$', 'START'), (r'(Back|View|Share|Create|Minus)$', 'BACK'),
    (r'L4$', 'L4'), (r'L5$', 'L5'), (r'R4$', 'R4'), (r'R5$', 'R5'),
    # an Elite pad's paddles: upper and lower on each side
    (r'LeftGrip_Upper$', 'L4'), (r'LeftGrip_Lower$', 'L5'), (r'RightGrip_Upper$', 'R4'), (r'RightGrip_Lower$', 'R5'),
    (r'(LeftGrip|LGrip)$', 'LGRIP'), (r'(RightGrip|RGrip)$', 'RGRIP'),
    (r'CenterPad_\w+$', 'CPAD'), (r'LeftPad_\w+$', 'LPAD'), (r'RightPad_\w+$', 'RPAD'),
    (r'(Pro|Left|Right)?Gyro_\w+$', 'GYRO'),
]

def button(family, rest):
    face = FACE.get(family, DEFAULT_FACE)
    # the Steam Frame's controllers name each button's click and touch
    if family == 'SteamFrameController':
        rest = re.sub(r'^(A|B|X|Y|Menu|View|LeftBumper|RightBumper|LeftGrip|RightGrip)_(Click|Touch|Pull)$', r'\1', rest)
    if rest in face:
        return face[rest]
    # PlayStation pads: a touchpad, never a pair of trackpads
    if family in ('PS4', 'PS5') and re.match(r'(Left|Right)Pad_', rest):
        return 'CPAD'
    for pat, b in RULES:
        if re.match(pat, rest):
            return b
    return None

def main():
    text = open(sys.argv[1], encoding='utf-8', errors='replace').read()
    rows = []
    for v, name in origins(text):
        fam, _, rest = name.partition('_')
        if fam not in FAMILY or not rest:
            continue
        b = button(fam, rest)
        if b:
            rows.append((v, FAMILY[fam], b, name))
    print('/* Generated by tools/steaminput/gen_origins.py from the order of the')
    print(' * Steamworks EInputActionOrigin enum: each origin Steam reports, as the')
    print(' * glyph set and the button that show it. Do not edit. */')
    print('#define SI_ORIGIN_TABLE_COUNT %d' % len(rows))
    print('static const struct { unsigned short origin; unsigned char set, button; } si_origin_table[] = {')
    for v, f, b, name in rows:
        print('\t{%d, SI_SET_%s, SI_BTN_%s}, /* %s */' % (v, f, b, name))
    print('};')

if __name__ == '__main__':
    main()
